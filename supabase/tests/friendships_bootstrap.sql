-- LOCAL THROWAWAY DATABASE ONLY. Never run this bootstrap in Supabase.
-- Minimal Supabase-shaped roles/auth fixture, not the real Auth service.
create role anon;
create role authenticated;
create schema auth;
create table auth.users (id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;
grant usage on schema public, auth to anon, authenticated;
create table public."User" (
  "UserID" uuid primary key references auth.users(id) on delete cascade,
  "Username" text,
  "Password" text
);
alter table public."User" enable row level security;
grant select ("UserID") on public."User" to authenticated;
create policy profile_own_read on public."User" for select to authenticated using ("UserID" = auth.uid());
create table public."Friends" (
  "FriendshipID" bigint generated by default as identity not null,
  "FriendUserID" uuid not null,
  "UserID" uuid,
  constraint "Friends_pkey" primary key ("FriendshipID"),
  constraint "Friends_UserID_fkey" foreign key ("UserID") references public."User"("UserID") on update cascade on delete cascade,
  constraint "Friends_FriendUserID_fkey" foreign key ("FriendUserID") references public."User"("UserID") on update cascade on delete cascade
);
grant all on public."Friends" to anon, authenticated;
-- Mimic Supabase defaults: the migration must remove these broad privileges.
alter default privileges in schema public grant all on tables to anon, authenticated;
alter default privileges in schema public grant all on sequences to anon, authenticated;
